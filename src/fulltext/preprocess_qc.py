"""Preprocessing quality metrics for extracted fulltext JSON (EN and DE).

Reads the manifest and per-book JSON, counts residual hyphenation, repeated
short paragraphs (likely running headers), and encoding damage. Writes:

  data/interim/fulltext/preprocess_qc.csv
  data/interim/fulltext/preprocess_qc.md

Usage:
  python -m src.fulltext.preprocess_qc
  python -m src.fulltext.preprocess_qc --lang de
  python -m src.fulltext.preprocess_qc --tag pre_clean
"""
from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

import pandas as pd

from src.common.logging_util import setup_logger
from src.common.paths import ROOT
from src.fulltext.books import FULLTEXT_DIR, JSON_DIR, MANIFEST_PATH, word_count
from src.fulltext.cleaning import (
    DEFAULT_MAX_HEADER_WORDS,
    DEFAULT_MIN_REPEATS,
    RULES_VERSION,
    count_cross_paragraph_hyphens,
    count_repeated_short_paragraphs,
    count_residual_hyphens,
)
from src.fulltext.extract_ebook import MOJIBAKE

QC_CSV = FULLTEXT_DIR / "preprocess_qc.csv"
QC_MD = FULLTEXT_DIR / "preprocess_qc.md"


def book_metrics(path: Path, row: dict) -> dict:
    record = json.loads(path.read_text(encoding="utf-8"))
    paragraphs = [p for c in record.get("chapters", []) for p in c.get("paragraphs", [])]
    text = " ".join(paragraphs)
    within_r, within_p = 0, 0
    for p in paragraphs:
        r, pr = count_residual_hyphens(p)
        within_r += r
        within_p += pr
    # Cross-paragraph splits counted per chapter (same scope as the cleaner).
    cross_r = cross_p = 0
    for chapter in record.get("chapters") or []:
        cr, cp = count_cross_paragraph_hyphens(chapter.get("paragraphs") or [])
        cross_r += cr
        cross_p += cp
    rejoinable = within_r + cross_r
    protected = within_p + cross_p
    header_hits, header_kinds = count_repeated_short_paragraphs(
        paragraphs, min_repeats=DEFAULT_MIN_REPEATS, max_words=DEFAULT_MAX_HEADER_WORDS,
    )
    n_words = int(record.get("n_words") or word_count(text))
    cleaning = (record.get("extraction") or {}).get("cleaning") or {}
    return {
        "book_id": row["book_id"],
        "lang": row["lang"],
        "corpus_role": row.get("corpus_role", ""),
        "format": row.get("format", record.get("format", "")),
        "extraction_status": row.get("extraction_status", ""),
        "text_layer": row.get("text_layer", ""),
        "n_words": n_words,
        "n_paragraphs": len(paragraphs),
        "n_chapters": len(record.get("chapters") or []),
        "chapter_source": (record.get("extraction") or {}).get("chapter_source", ""),
        "residual_hyphen_rejoinable": rejoinable,
        "residual_hyphen_within": within_r,
        "residual_hyphen_cross_paragraph": cross_r,
        "residual_hyphen_protected": protected,
        "residual_hyphen_per_10k": round(rejoinable / n_words * 10_000, 3) if n_words else 0.0,
        "repeated_header_paragraphs": header_hits,
        "repeated_header_kinds": header_kinds,
        "repeated_header_share": round(header_hits / len(paragraphs), 4) if paragraphs else 0.0,
        "replacement_chars": text.count("\ufffd"),
        "mojibake": len(MOJIBAKE.findall(text)),
        "cleaning_rules_version": cleaning.get("rules_version", ""),
        "json_path": str(path.relative_to(ROOT)),
    }


def write_summary(df: pd.DataFrame, tag: str, log) -> None:
    lines = [
        "# Fulltext preprocessing QC",
        "",
        f"Generated by `python -m src.fulltext.preprocess_qc` on {date.today().isoformat()}"
        + (f" (tag=`{tag}`)." if tag else "."),
        "",
        f"Cleaning rules version expected after cleaner: `{RULES_VERSION}`. "
        f"Header heuristic: short paragraphs (≤{DEFAULT_MAX_HEADER_WORDS} words) "
        f"repeating ≥{DEFAULT_MIN_REPEATS} times.",
        "",
        "## Books with JSON by language and role",
        "",
    ]
    if df.empty:
        lines += ["No extracted books found.", ""]
    else:
        lines += [
            df.groupby(["lang", "corpus_role"]).size().rename("books").reset_index()
            .to_markdown(index=False),
            "",
            "## Residual hyphenation (rejoinable) per 10k words",
            "",
            df.groupby("lang")["residual_hyphen_per_10k"]
            .describe(percentiles=[0.5, 0.9])[["count", "mean", "50%", "90%", "max"]]
            .round(3).to_markdown(),
            "",
            "## Protected coordinated compounds (kept; not errors)",
            "",
            df.groupby("lang")["residual_hyphen_protected"].sum().rename("total")
            .reset_index().to_markdown(index=False),
            "",
            "## Repeated short paragraphs (likely headers/footers)",
            "",
            df.groupby("lang")[["repeated_header_paragraphs", "repeated_header_share"]]
            .agg({"repeated_header_paragraphs": "sum", "repeated_header_share": "mean"})
            .round(4).to_markdown(),
            "",
            "## Encoding (books with >20 replacement or mojibake chars)",
            "",
        ]
        enc = df[(df["replacement_chars"] > 20) | (df["mojibake"] > 20)]
        lines += [
            enc[["book_id", "lang", "replacement_chars", "mojibake"]].to_markdown(index=False)
            if not enc.empty else "None.",
            "",
            "## Cleaner rules_version on JSON",
            "",
            df.groupby(["lang", "cleaning_rules_version"]).size().rename("books")
            .reset_index().to_markdown(index=False),
            "",
            "## Worst residual-hyphen books (top 10 per language)",
            "",
        ]
        for lang in sorted(df["lang"].unique()):
            top = (df[df["lang"] == lang]
                   .sort_values("residual_hyphen_rejoinable", ascending=False)
                   .head(10))
            lines += [
                f"### {lang}",
                "",
                top[["book_id", "corpus_role", "format", "residual_hyphen_rejoinable",
                     "residual_hyphen_per_10k", "repeated_header_paragraphs"]]
                .to_markdown(index=False),
                "",
            ]
    QC_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    log.info(f"wrote {QC_MD}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--lang", choices=["en", "de", "other", "all"], default="all")
    parser.add_argument("--tag", default="", help="label stored in a sidecar note in the markdown")
    parser.add_argument("--limit", type=int, default=0, help="at most N books (0 = all)")
    args = parser.parse_args()
    log = setup_logger(__file__)

    manifest = pd.read_csv(MANIFEST_PATH, dtype=str, encoding="utf-8").fillna("")
    books = manifest[manifest["extraction_status"] == "ok"].copy()
    if args.lang != "all":
        books = books[books["lang"] == args.lang]

    rows = []
    for i, row in enumerate(books.to_dict(orient="records"), 1):
        path = JSON_DIR / row["lang"] / f"{row['book_id']}.json"
        if not path.is_file():
            continue
        rows.append(book_metrics(path, row))
        if args.limit and len(rows) >= args.limit:
            break
        if i % 100 == 0:
            log.info(f"  {i}/{len(books)}")

    df = pd.DataFrame(rows)
    if args.tag and not df.empty:
        df.insert(0, "tag", args.tag)
    FULLTEXT_DIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(QC_CSV, index=False, encoding="utf-8")
    log.info(f"wrote {QC_CSV} ({len(df)} books)")
    write_summary(df.drop(columns=["tag"], errors="ignore") if "tag" in df.columns else df,
                  args.tag, log)
    if not df.empty:
        log.info(
            "residual_hyphen_per_10k by lang:\n"
            + df.groupby("lang")["residual_hyphen_per_10k"].mean().round(3).to_string()
        )
    log.close()


if __name__ == "__main__":
    main()
